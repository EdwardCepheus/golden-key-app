# Helper to map data
def process():
    f = io.StringIO(raw_data)
    reader = csv.reader(f)
    
    products = {}
    for row in reader:
        if not row: continue
        num_iid = row[0]
        if num_iid not in products:
            # For products with multiple rows (SKUs), we capture the first selling price and combine attributes into description
            products[num_iid] = {
                'id': str(uuid.uuid4()),
                'num_iid': num_iid,
                'category_id': row[1],
                'category_name': row[2],
                'title_zh': row[3],
                'title_en': '',
                'guide_title': row[5] if len(row) > 5 and '颜色分类' not in row[5] else '',
                'description_zh': f"淘宝导入产品。分类：{row[2]}。原始标题：{row[3]}",
                'description_en': '',
                'cost_price': 0.0,
                'logistics_cost': 0.0,
                'packaging_cost': 0.0,
                'platform_commission': 0.0,
                'selling_price': float(row[4]) if row[4] else 0.0,
                'merchant_code': '',
                'images': '[]',
                'content_blocks': '[]',
                'tags': json.dumps(row[2].split('>>')),
                'created_at': datetime.datetime.now().isoformat(),
                'updated_at': datetime.datetime.now().isoformat()
            }
        else:
            # Append SKU info to description for richer context
            if len(row) > 7:
                products[num_iid]['description_zh'] += f"\nSKU属性：{row[7]}"
    
    db_path = "/Users/cepheus/Library/Application Support/com.goldenkey.app/golden_key.db"
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    # First clear existing to avoid dupes if running again
    # cursor.execute("DELETE FROM products")
    
    count = 0
    for p in products.values():
        cursor.execute('''
            INSERT OR REPLACE INTO products (
                id, num_iid, category_id, category_name, title_zh, title_en, guide_title, 
                description_zh, description_en, cost_price, logistics_cost, packaging_cost, 
                platform_commission, selling_price, merchant_code, images, content_blocks, 
                tags, created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            p['id'], p['num_iid'], p['category_id'], p['category_name'], p['title_zh'], 
            p['title_en'], p['guide_title'], p['description_zh'], p['description_en'], 
            p['cost_price'], p['logistics_cost'], p['packaging_cost'], 
            p['platform_commission'], p['selling_price'], p['merchant_code'], 
            p['images'], p['content_blocks'], p['tags'], p['created_at'], p['updated_at']
        ))
        count += 1
    
    conn.commit()
    conn.close()
    print(f"Successfully imported {count} products from CSV.")

if __name__ == "__main__":
    process()
